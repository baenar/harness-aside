#!/bin/sh
# Regenerates the tool-window animation frames in src/main/resources/icons.
#
# Every frame is a plain SVG file so the IDE loads it through IconLoader like any other
# icon. An earlier version derived frames at paint time from one file with a custom
# javax.swing.Icon and Graphics2D transforms; the platform renders those at the wrong size
# on a tool-window button, so frames are baked into files instead.
#
# Run after changing the glyph:  sh tools/generate-icons.sh
set -eu

DIR="$(dirname "$0")/../src/main/resources/icons"
WALK_FRAMES=12
KICK_FRAMES=8

# Claude Code glyph. Spans x 0..24, y 5..20 in its own coordinates.
GLYPH='M20.998 10.949H24v3.102h-3v3.028h-1.487V20H18v-2.921h-1.487V20H15v-2.921H9V20H7.488v-2.921H6V20H4.487v-2.921H3V14.05H0V10.95h3V5h17.998v5.949zM6 10.949h1.488V8.102H6v2.847zm10.51 0H18V8.102h-1.49v2.847z'

# Scaled to 80% and centred in a 24x24 box, so the walk has a visible gap between passes
# and a 180-degree rotation lands back on the same spot.
FIT='translate(2.4, 2) scale(0.8)'

# $1 = file, $2 = comment, $3.. = one <g> transform per copy of the glyph
emit() {
    file="$DIR/$1"
    comment="$2"
    shift 2
    {
        echo '<svg xmlns="http://www.w3.org/2000/svg" width="13" height="13" viewBox="0 0 24 24">'
        echo "  <!-- $comment Generated by tools/generate-icons.sh - do not edit. -->"
        for transform in "$@"; do
            echo "  <g transform=\"$transform\">"
            echo "    <g transform=\"$FIT\">"
            echo "      <path clip-rule=\"evenodd\" fill=\"#FFFFFF\" fill-rule=\"evenodd\""
            echo "            d=\"$GLYPH\" />"
            echo '    </g>'
            echo '  </g>'
        done
        echo '</svg>'
    } > "$file"
}

i=0
while [ "$i" -lt "$WALK_FRAMES" ]; do
    dx=$(awk -v i="$i" -v n="$WALK_FRAMES" 'BEGIN { printf "%.3f", 24 * i / n }')
    dx_prev=$(awk -v d="$dx" 'BEGIN { printf "%.3f", d - 24 }')
    emit "$(printf 'walk_%02d.svg' "$i")" \
        "Walk frame $i of $WALK_FRAMES: the glyph slides right; a second copy a width behind keeps the button filled as the first leaves." \
        "translate($dx, 0)" "translate($dx_prev, 0)"
    i=$((i + 1))
done

i=0
while [ "$i" -lt "$KICK_FRAMES" ]; do
    # Upside down, rocking +/-16 degrees, riding a half-speed bob so it looks like kicking
    # rather than spinning in place.
    angle=$(awk -v i="$i" -v n="$KICK_FRAMES" 'BEGIN { printf "%.2f", 180 + sin(2 * 3.14159265 * i / n) * 16 }')
    bob=$(awk -v i="$i" -v n="$KICK_FRAMES" 'BEGIN { printf "%.2f", sin(3.14159265 * i / n) * 1.4 }')
    emit "$(printf 'kick_%02d.svg' "$i")" \
        "Kick frame $i of $KICK_FRAMES: flipped upside down, rocked $angle degrees about the centre." \
        "rotate($angle 12 12) translate(0, $bob)"
    i=$((i + 1))
done

echo "wrote $WALK_FRAMES walk + $KICK_FRAMES kick frames to $DIR"
